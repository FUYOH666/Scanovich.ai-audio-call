// Language functionality
let currentLang = localStorage.getItem('preferred-language') || 'ru';

function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('preferred-language', lang);
    
    // Update active language button
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.dataset.lang === lang) {
            btn.classList.add('active');
        }
    });
    
    // Update all translatable elements
    updateTranslations();
    
    // Update calculator with new currency
    if (typeof updateCalculator === 'function') {
        updateCalculator();
    }
    
    // Update URL parameter
    const url = new URL(window.location);
    url.searchParams.set('lang', lang);
    window.history.replaceState({}, '', url);
}

function updateTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        const translation = translations[currentLang][key];
        if (translation) {
            element.textContent = translation;
        }
    });
    
    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        const translation = translations[currentLang][key];
        if (translation) {
            element.placeholder = translation;
        }
    });
    
    // Update page title
    document.title = translations[currentLang]['page-title'] || 'Scanovich.ai';
}

function initTranslations() {
    // Get language from URL parameter
    const urlParams = new URLSearchParams(window.location.search);
    const langParam = urlParams.get('lang');
    if (langParam && translations[langParam]) {
        currentLang = langParam;
        localStorage.setItem('preferred-language', langParam);
    }
    
    // Set active language button
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.dataset.lang === currentLang) {
            btn.classList.add('active');
        }
    });
    
    // Apply translations
    updateTranslations();
}

// Auto-initialize on load
document.addEventListener('DOMContentLoaded', initTranslations);